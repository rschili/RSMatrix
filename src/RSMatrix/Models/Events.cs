using System.Text.Json;
using System.Text.Json.Serialization;

namespace RSMatrix.Models;

internal class BasicEvent
{
    [JsonPropertyName("content")]
    public JsonElement? Content { get; set; }
    [JsonPropertyName("type")]
    public required string Type { get; set; }
    [JsonPropertyName("sender")]
    public string? Sender { get; set; }

    [JsonExtensionData]
    public Dictionary<string, JsonElement>? AdditionalProps { get; set; }
}

internal class RoomEvent
{
    [JsonPropertyName("content")]
    public required JsonElement? Content { get; set; }

    [JsonPropertyName("type")]
    public required string Type { get; set; }

    [JsonPropertyName("sender")]
    public required string Sender { get; set; }

    [JsonPropertyName("event_id")]
    public required string EventId { get; set; }

    [JsonPropertyName("origin_server_ts")]
    public required long OriginServerTs { get; set; }

    /// <summary>
    /// Only set if it's a state event.
    /// </summary>
    [JsonPropertyName("state_key")]
    public string? StateKey { get; set; }

    [JsonPropertyName("unsigned")]
    public UnsignedData? Unsigned { get; set; }

    [JsonPropertyName("room_id")]
    public string? RoomId { get; set; }

    /// <summary>
    /// The redacted event, for redactions in rooms before version 11. Later versions put it into the content.
    /// Servers set both for compatibility.
    /// </summary>
    [JsonPropertyName("redacts")]
    public string? Redacts { get; set; }

    [JsonExtensionData]
    public Dictionary<string, JsonElement>? AdditionalProps { get; set; }
}

